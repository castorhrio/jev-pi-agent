/**
 * i18n core, shared by the Electron main process (for the native menu) and the
 * Renderer (for the UI). Keeping one dictionary for both is what makes a menu
 * item and the page it opens say the same thing in the same language.
 *
 * No i18n framework: a flat dictionary with dot keys and `{name}` interpolation
 * is enough, and it keeps the bundle free of a dependency that would have to
 * agree with the Renderer's CSP.
 */

export const LOCALES = ['zh-CN', 'en-US'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'zh-CN';

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (LOCALES as readonly string[]).includes(value);
}

/** Picks the best supported locale for a system language list. */
export function negotiateLocale(candidates: readonly string[]): Locale {
  for (const raw of candidates) {
    const tag = raw.toLowerCase();
    if (tag.startsWith('zh')) {
      // Traditional Chinese is not shipped; Simplified is the honest default
      // rather than silently falling back to English.
      return 'zh-CN';
    }
    if (tag.startsWith('en')) return 'en-US';
  }
  return DEFAULT_LOCALE;
}

