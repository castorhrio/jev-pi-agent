export const DICTIONARIES: Record<Locale, Dictionary> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export function dictionaryFor(locale: Locale): Dictionary {
  return DICTIONARIES[locale] ?? DICTIONARIES[DEFAULT_LOCALE];
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

/**
 * Looks a key up, then interpolates `{name}` placeholders.
 *
 * A missing key returns the key itself rather than an empty string: a visible
 * `welcome.step2` in the UI is a bug report, whereas a blank button is a ghost.
 */
export function createTranslator(locale: Locale): Translate {
  const dict = dictionaryFor(locale);
  return (key, vars) => {
    const template = dict[key] ?? DICTIONARIES[DEFAULT_LOCALE][key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => {
      const value = vars[name];
      return value === undefined ? match : String(value);
    });
  };
}
